_SOURCE = '''\
import os


class Outer:
    """Sinif."""

    @property
    def method(self, path, mode="r"):
        """Open the file at the given path safely.

        Longer description.
        """
        # yorum
        if not path:
            raise ValueError("bos yol")
        with open(path, mode) as f:
            data = f.read()
        return data.strip()

    class Inner:
        def deep(self, x):
            """Return twice the given value plus one."""
            y = x * 2
            if y > 10:
                y -= 1
            z = y + 1
            return z


def top(a, b):
    """Add two numbers and return the result please."""
    c = a + b
    d = c * 1
    e = d - 0
    return e


def short_doc(a):
    """Too short."""
    b = a
    c = b
    d = c
    return d
'''


def test_extract_methods_and_top_level():
    out = {q: rec for q, a, b, rec in rw.extract_from_source(_SOURCE)}
    assert set(out) == {"Outer.method", "Outer.Inner.deep", "top"}
    m = out["Outer.method"]
    assert m["func_name"] == "method"
    assert m["signature"] == 'def method(self, path, mode="r"):'
    assert m["docstring"].startswith("Open the file")
    # Dekorator, docstring ve yorum yok; sola yasli, govde 4 bosluk.
    assert m["code"].startswith("def method(")
    assert "@property" not in m["code"] and "#" not in m["code"] and '"""' not in m["code"]
    fn = ast.parse(m["code"]).body[0]
    assert fn.col_offset == 0 and fn.body[0].col_offset == 4


def test_method_format_matches_csn_style():
    """Metot, CSN bicimine (yalnizca def satiri sola yasli) uygulanan
    normalize_code ile birebir ayni sonucu vermeli; yani human.jsonl bicimi."""
    lines = _SOURCE.splitlines()
    tree = ast.parse(_SOURCE)
    fn = tree.body[1].body[1]
    seg = lines[fn.lineno - 1: fn.end_lineno]
    csn_style = seg[0].lstrip() + "\n" + "\n".join(seg[1:]) + "\n"
    expected = normalize_code(csn_style)
    out = {q: rec for q, a, b, rec in rw.extract_from_source(_SOURCE)}
    assert out["Outer.method"]["code"] == expected


def test_cut_function_falls_back_for_left_aligned_strings():
    src = (
        "class A:\n"
        "    def f(self):\n"
        "        \"\"\"Return a fixed multi line text value.\"\"\"\n"
        "        s = '''\n"
        "sola yasli\n"
        "'''\n"
        "        t = s\n"
        "        u = t\n"
        "        return u\n"
    )
    fn = ast.parse(src).body[0].body[0]
    code = rw.cut_function(src.splitlines(), fn)
    assert code is not None and code.startswith("def f(self):")
    norm = normalize_code(code)
    assert norm is not None
    assert ast.parse(norm).body[0].body[0].col_offset == 4


def test_human_jsonl_format_if_present():
    """Uretilmis veri varsa: alanlar ve bicim human.jsonl ile uyumlu."""
    recs = rw.load_jsonl(rw.RW_HUMAN)
    if not recs:
        pytest.skip("data/real_world/human.jsonl yok")
    base = {"id", "func_name", "signature", "docstring", "code", "repo", "url", "label"}
    extra = {"project", "version", "release_date", "source"}
    for r in recs:
        assert base | extra <= set(r)
        assert r["label"] == 0 and r["source"] == "human_realworld"
        assert normalize_code(r["code"]) == r["code"]
        assert ast.parse(r["code"]).body[0].col_offset == 0
        assert 5 <= len(r["code"].splitlines()) <= 60
        assert rw.in_window(datetime.fromisoformat(r["release_date"]).replace(tzinfo=timezone.utc))
    assert len({r["code"] for r in recs}) == len(recs)
    train = rw.load_jsonl(rw.HUMAN_JSONL)
    if train:
        assert not {r["repo"] for r in recs} & {r["repo"] for r in train}
        assert not {r["code"] for r in recs} & {r["code"] for r in train}


