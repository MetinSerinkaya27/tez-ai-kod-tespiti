def test_skeleton_prompt_uses_02_template():
    gen = rw.load_gen_module()
    r = _rec("def g(x):", "Apply the given function to every element.", "g")
    p = rw.build_prompt(gen, r, "skeleton")
    assert p == gen.PROMPT.format(skeleton=gen.skeleton(r))
    assert "def g(x):" in p and "Apply the given function" in p
    with pytest.raises(ValueError):
        rw.build_prompt(gen, r, "baska")
