def _rec(sig, doc, name):
    return {"signature": sig, "docstring": doc, "func_name": name}


def test_natural_prompt_drops_self_and_conjugates():
    r = _rec("def add_edge(self, u, v, weight: float = 1.0):",
             "Add an edge between u and v.\n\nMore details here.", "add_edge")
    assert rw.natural_prompt(r) == (
        "Write a Python function `add_edge(u, v, weight: float=1.0)` "
        "that adds an edge between u and v.")


def test_natural_prompt_variants():
    r = _rec("def endpoint(self):", "The endpoint that matched the request.", "endpoint")
    assert rw.natural_prompt(r).endswith("that returns the endpoint that matched the request.")
    r = _rec("def f(cls, *args, **kw):", "Returns True if the edge exists. Otherwise no.", "f")
    assert rw.natural_prompt(r) == (
        "Write a Python function `f(*args, **kw)` that returns True if the edge exists.")
    r = _rec("def g(x):", "Apply the given function\nto every element of x.", "g")
    assert rw.natural_prompt(r).endswith("that applies the given function to every element of x.")
    # Docstring ve govde istemde yok (yalnizca ilk cumle).
    assert "\n" not in rw.natural_prompt(r)


