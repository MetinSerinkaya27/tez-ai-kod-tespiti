def load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def in_window(date: datetime, lo: datetime = DATE_MIN, hi: datetime = DATE_MAX) -> bool:
    """Yayin tarihi [lo, hi] araliginda mi (ChatGPT oncesi pencere)."""
    return lo <= date <= hi


def norm_repo(repo: str) -> str:
    return repo.strip().lower()


def excluded_reason(repo: str, train_repos: set[str], csn_repos: set[str]) -> str | None:
    """Depo egitimde/CSN'de varsa ya da ayni adli bir CSN deposu varsa sebep dondurur."""
    r = norm_repo(repo)
    train = {norm_repo(x) for x in train_repos}
    csn = {norm_repo(x) for x in csn_repos}
    if r in train:
        return "egitim_deposu"
    if r in csn:
        return "csn_deposu"
    base = r.split("/")[-1]
    if base in {x.split("/")[-1] for x in train | csn}:
        return "csn_ayni_ad"
    return None


def is_skipped_path(path: str) -> bool:
    """Test/vendor/uretilmis/migration/dokuman dosyalari atlanir."""
    return bool(_SKIP_PATH_RE.search(path))


class _RangeFile(io.RawIOBase):
    """HTTP Range istekleriyle okunan dosya; parquet'ten tek sutun okumak icin."""

    def __init__(self, url: str):
        self.session = requests.Session()
        r = self.session.get(url, headers={"Range": "bytes=0-0"}, timeout=60)
        r.raise_for_status()
        self.url = r.url
        self.size = int(r.headers["Content-Range"].split("/")[1])
        self.pos = 0

    def seekable(self): return True
    def readable(self): return True
    def tell(self): return self.pos

    def seek(self, off, whence=0):
        self.pos = off if whence == 0 else (self.pos + off if whence == 1 else self.size + off)
        return self.pos

    def read(self, n=-1):
        if n is None or n < 0:
            n = self.size - self.pos
        if n == 0 or self.pos >= self.size:
            return b""
        end = min(self.pos + n, self.size) - 1
        r = self.session.get(self.url, headers={"Range": f"bytes={self.pos}-{end}"}, timeout=120)
        r.raise_for_status()
        self.pos += len(r.content)
        return r.content

    def readinto(self, b):
        d = self.read(len(b))
        b[: len(d)] = d
        return len(d)


def load_csn_repos() -> set[str]:
    """CodeSearchNet Python (train+validation+test) depo adlari; ilk seferde indirilir."""
    if CSN_REPOS.exists():
        return {x for x in CSN_REPOS.read_text(encoding="utf-8").split("\n") if x}
    import pyarrow.parquet as pq

    names: set[str] = set()
    if CSN_TEST_PARQUET.exists():
        names |= set(pq.read_table(CSN_TEST_PARQUET, columns=["repository_name"])
                     .column(0).to_pylist())
    splits = ("train", "validation") if names else ("train", "validation", "test")
    for split in splits:
        print(f"CSN {split} depo adlari okunuyor (yalnizca bir sutun, Range istekleri)...")
        pf = pq.ParquetFile(_RangeFile(CSN_SPLIT_URL.format(split=split)))
        for i in range(pf.metadata.num_row_groups):
            names |= set(pf.read_row_group(i, columns=["repository_name"]).column(0).to_pylist())
    REAL.mkdir(parents=True, exist_ok=True)
    CSN_REPOS.write_text("\n".join(sorted(names)) + "\n", encoding="utf-8")
    return names


def pypi_release_date(name: str, version: str) -> datetime:
    """Surumun PyPI'a ilk yuklenme zamani (UTC)."""
    r = requests.get(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30)
    r.raise_for_status()
    times = [u["upload_time_iso_8601"] for u in r.json()["urls"]]
    return min(datetime.fromisoformat(t.replace("Z", "+00:00")) for t in times)


def download_archive(repo: str, tag: str) -> Path:
    ARCHIVES.mkdir(parents=True, exist_ok=True)
    path = ARCHIVES / f"{repo.replace('/', '__')}__{tag}.tar.gz"
    if path.exists():
        return path
    url = f"https://codeload.github.com/{repo}/tar.gz/refs/tags/{tag}"
    tmp = path.with_suffix(".part")
    with requests.get(url, stream=True, timeout=120) as r:
        r.raise_for_status()
        with open(tmp, "wb") as f:
            for chunk in r.iter_content(1 << 20):
                f.write(chunk)
    tmp.replace(path)
    return path


def read_archive(path: Path) -> tuple[dict[str, str], datetime, str | None]:
    """Arsivi diske acmadan okur: {goreli yol: kaynak}, etiket commit tarihi, commit sha.

    GitHub tarball'larinda her girdinin mtime'i etiket commit'inin tarihidir;
    pax genel basligindaki 'comment' alani commit sha'sidir.
    """
    files: dict[str, str] = {}
    mtimes: list[int] = []
    with tarfile.open(path, "r:gz") as tf:
        sha = tf.pax_headers.get("comment")
        for m in tf:
            mtimes.append(int(m.mtime))
            if not m.isfile() or not m.name.endswith(".py"):
                continue
            rel = m.name.split("/", 1)[1] if "/" in m.name else m.name
            data = tf.extractfile(m).read()
            try:
                files[rel] = data.decode("utf-8")
            except UnicodeDecodeError:
                continue
    commit_date = datetime.fromtimestamp(max(mtimes), tz=timezone.utc)
    return files, commit_date, sha


