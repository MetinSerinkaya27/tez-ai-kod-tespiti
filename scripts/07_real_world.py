def _iter_functions(tree: ast.Module):
    """Ust duzey fonksiyonlar ve (ic ice siniflar dahil) sinif metotlari."""
    stack = [(tree, "")]
    while stack:
        node, prefix = stack.pop()
        for child in node.body:
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                yield child, prefix + child.name
            elif isinstance(child, ast.ClassDef):
                stack.append((child, f"{prefix}{child.name}."))


def cut_function(lines: list[str], fn: ast.AST) -> str | None:
    """Kaynaktan 'def' satirindan bitise kadar keser (dekoratorler haric) ve sola yaslar.

    Once tum blok dedent edilir; govdede sola yaslanmis cok satirli dizgi gibi
    durumlarda bu ise yaramazsa CSN bicimine (yalnizca ilk satir sola yasli)
    donulur ve normalize_code'un girinti duzeltmesine birakilir.
    """
    seg = lines[fn.lineno - 1: fn.end_lineno]
    text = "\n".join(seg) + "\n"
    ded = textwrap.dedent(text.expandtabs(4))
    try:
        ast.parse(ded)
        return ded
    except SyntaxError:
        pass
    csn_style = seg[0].lstrip() + "\n" + "\n".join(seg[1:]) + "\n"
    try:
        ast.parse(csn_style)
    except SyntaxError:
        return None
    return csn_style


def build_record(code: str, func_name: str) -> dict | None:
    """01_build_human.build_record ile ayni filtreler; meta alanlari cagiran ekler."""
    try:
        header = function_header(code)
    except (SyntaxError, ValueError):
        return None
    if header is None:
        return None
    signature, doc = header
    if len(doc.split()) < MIN_DOC_WORDS:
        return None
    norm = normalize_code(code)
    if norm is None:
        return None
    if not MIN_LINES <= len(norm.splitlines()) <= MAX_LINES:
        return None
    return {"func_name": func_name, "signature": signature, "docstring": doc, "code": norm}


def extract_from_source(source: str) -> list[tuple[str, int, int, dict]]:
    """Kaynak dosyadan (qualname, ilk satir, son satir, kayit) listesi."""
    if _GENERATED_RE.search("\n".join(source.splitlines()[:10])):
        return []
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError):
        return []
    lines = source.replace("\r\n", "\n").splitlines()
    out = []
    for fn, qual in _iter_functions(tree):
        code = cut_function(lines, fn)
        if code is None:
            continue
        rec = build_record(code, fn.name)
        if rec is not None:
            out.append((qual, fn.lineno, fn.end_lineno, rec))
    return out


def cmd_human(args) -> None:
    train = load_jsonl(HUMAN_JSONL)
    train_repos = {r["repo"] for r in train}
    train_codes = {r["code"] for r in train}
    csn_repos = load_csn_repos()
    print(f"Haric tutulan: {len(train_repos)} egitim deposu, {len(csn_repos)} CSN deposu")

    rng = random.Random(SEED)
    records, meta, seen = [], [], set(train_codes)
    for p in PROJECTS:
        reason = excluded_reason(p["repo"], train_repos, csn_repos)
        if reason:
            print(f"ATLANDI {p['repo']}: {reason}")
            continue
        release = pypi_release_date(p["pypi"], p["version"])
        archive = download_archive(p["repo"], p["tag"])
        files, commit_date, sha = read_archive(archive)
        if not in_window(release) or not in_window(commit_date):
            print(f"ATLANDI {p['repo']}: tarih penceresi disinda ({release}, {commit_date})")
            continue

        cands, n_files = [], 0
        for rel in sorted(files):
            if is_skipped_path(rel):
                continue
            n_files += 1
            for qual, a, b, rec in extract_from_source(files[rel]):
                if rec["code"] in seen:
                    continue
                seen.add(rec["code"])
                cands.append((rel, qual, a, b, rec))
        rng.shuffle(cands)
        chosen = cands[: args.per_project]
        project = p["repo"].split("/")[-1]
        for rel, qual, a, b, rec in chosen:
            key = f"{p['repo']}@{p['tag']}:{rel}:{qual}"
            records.append({
                "id": hashlib.sha1(key.encode()).hexdigest()[:12],
                **rec,
                "repo": p["repo"],
                "url": f"https://github.com/{p['repo']}/blob/{p['tag']}/{rel}#L{a}-L{b}",
                "label": 0,
                "project": project,
                "version": p["version"],
                "release_date": release.date().isoformat(),
                "source": "human_realworld",
            })
        meta.append({**p, "project": project, "release_date": release.isoformat(),
                     "tag_commit_date": commit_date.isoformat(), "commit": sha,
                     "py_files": n_files, "candidates": len(cands), "taken": len(chosen)})
        print(f"{p['repo']:22s} {p['version']:8s} yayin {release.date()} "
              f"commit {commit_date.date()} dosya {n_files:4d} aday {len(cands):4d} "
              f"alinan {len(chosen)}")

    REAL.mkdir(parents=True, exist_ok=True)
    with open(RW_HUMAN, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    RW_PROJECTS.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Toplam {len(records)} insan kaydi -> {RW_HUMAN}")


